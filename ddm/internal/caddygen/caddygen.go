// Package caddygen writes the Caddyfile from the spec's mounts. It replaces
// the old hand-written file and its per-request filesystem probing: every
// mount knows exactly which published directory it serves.
package caddygen

import (
	"fmt"
	"maps"
	"slices"
	"strings"

	"ddm/internal/bar"
	"ddm/internal/publish"
	"ddm/internal/robots"
	"ddm/internal/spec"
)

// Target says what the Caddyfile is for.
type Target struct {
	// Preview serves every host over plain http on Port, as
	// <host>.localhost (browsers resolve *.localhost to this machine), with
	// no certificates and no tailnet checks. Otherwise it is the production
	// config.
	Preview bool
	Port    int
	// WWW is the publish root the config points into.
	WWW string
	// AuthSocket is Tailscale's auth helper (NixOS services.tailscaleAuth),
	// which private mounts ask who the client is. Prod only.
	AuthSocket string
}

// DefaultAuthSocket is services.tailscaleAuth's default socket path.
const DefaultAuthSocket = "/run/tailscale-nginx-auth/tailscale-nginx-auth.sock"

// Tailscale's address ranges: private mounts refuse anything else.
const tailnetRanges = "100.64.0.0/10 fd7a:115c:a1e0::/48"

// Base is the URL a host is served at for this target.
func (t Target) Base(host string) string {
	if t.Preview {
		return fmt.Sprintf("http://%s:%d", PreviewHost(host), t.Port)
	}
	return "https://" + host
}

// PreviewHost is the name a host is served at in a preview.
func PreviewHost(host string) string { return host + ".localhost" }

// mount is a spec mount with its site attached.
type mount struct {
	spec.Mount
	Site   string
	Served string // the published name: the site, or its pool
	// For a pool member's own host (cloakaml.cathe.dev): its package's path
	// prefix, and the pool index's URL that everything else redirects to, so
	// odoc's "Index" and other packages open on the index host.
	Package, Index string
}

// block is one site block of the Caddyfile: a single host, or a wildcard
// whose hosts are told apart by matchers (so they share one certificate).
type block struct {
	Address string
	Private bool
	Hosts   map[string][]mount
}

// Generate returns the Caddyfile for s.
func Generate(s *spec.Spec, t Target) string {
	if t.AuthSocket == "" {
		t.AuthSocket = DefaultAuthSocket
	}
	var b strings.Builder
	w := func(depth int, format string, args ...any) {
		fmt.Fprintf(&b, "%s%s\n", strings.Repeat("\t", depth), fmt.Sprintf(format, args...))
	}

	w(0, "# Generated by ddm from sites.yaml (%s). Do not edit: run `ddm caddyfile`.", targetName(t))
	w(0, "{")
	if t.Preview {
		w(1, "admin off")
		w(1, "auto_https off")
		w(1, "default_bind 127.0.0.1 [::1]")
	} else {
		w(1, "acme_dns cloudflare {env.CLOUDFLARE_API_TOKEN}")
	}
	w(0, "}")

	// Every block shows the shared 404 page from the site directory.
	notFound := notFoundRoot(s, t.WWW)
	w(0, "")
	w(0, "(errors) {")
	if notFound != "" {
		w(1, "handle_errors 404 {")
		w(2, "root * %s", notFound)
		w(2, "rewrite * /404.html")
		w(2, "file_server")
		w(1, "}")
	}
	w(0, "}")

	for _, bl := range blocks(s, t) {
		w(0, "")
		w(0, "%s {", bl.Address)
		w(1, "import errors")
		d := 1
		if bl.Private {
			if t.Preview {
				w(1, "# private: in prod, only your Tailscale identity gets past here")
			} else {
				// route keeps the written order, so the gate runs first.
				w(1, "route {")
				d = 2
				private(w, d, t.AuthSocket)
				// In case a private address leaks: never index it.
				w(d, `header X-Robots-Tag "noindex, nofollow"`)
			}
		}
		hosts := slices.Sorted(maps.Keys(bl.Hosts))
		if len(hosts) == 1 && !strings.HasPrefix(bl.Address, "*.") {
			mounts(w, d, hosts[0], bl.Hosts[hosts[0]], s.Robots, t.WWW, bl.Private)
		} else {
			for _, h := range hosts {
				name := strings.NewReplacer(".", "_", "-", "_").Replace(h)
				w(d, "@%s host %s", name, h)
				w(d, "handle @%s {", name)
				mounts(w, d+1, h, bl.Hosts[h], s.Robots, t.WWW, bl.Private)
				w(d, "}")
			}
			w(d, "handle {")
			w(d+1, "error 404")
			w(d, "}")
		}
		if d == 2 {
			w(1, "}")
		}
		w(0, "}")
	}
	if t.Preview {
		// Any other host on the port gets the 404 page, as an unknown
		// subdomain does in prod.
		w(0, "")
		w(0, "http://:%d {", t.Port)
		w(1, "import errors")
		w(1, "error 404")
		w(0, "}")
	}
	return b.String()
}

func targetName(t Target) string {
	if t.Preview {
		return fmt.Sprintf("local preview on port %d", t.Port)
	}
	return "production"
}

// private gates a block on the client being on the tailnet and being the
// owner. Binding the block to the tailnet address alone isn't possible: on
// Linux a specific-address listener can't share :443 with the public
// blocks' wildcard listener.
func private(w func(int, string, ...any), d int, socket string) {
	w(d, "@outside not remote_ip %s", tailnetRanges)
	w(d, "abort @outside")
	// Never trust a client-sent identity header. The helper reports the full
	// login (you@github) as Tailscale-User; its Tailscale-Login is only the
	// part before the @, which other providers could share.
	w(d, "request_header -Tailscale-User")
	w(d, "forward_auth unix/%s {", socket)
	w(d+1, "uri /auth")
	w(d+1, "header_up Remote-Addr {remote_host}")
	w(d+1, "header_up Remote-Port {remote_port}")
	w(d+1, "header_up Original-URI {uri}")
	w(d+1, "copy_headers Tailscale-User")
	w(d, "}")
	// TAILNET_OWNER is your Tailscale login, set by the NixOS module. Unset,
	// nobody is the owner: the gate fails closed.
	w(d, "@notowner expression `{http.request.header.Tailscale-User} != {env.TAILNET_OWNER} || {env.TAILNET_OWNER} == ''`")
	w(d, "error @notowner 403")
}

// mounts writes the handlers for one host's mounts, longest path first,
// after its robots.txt and the toolbar's files (/_ddm/, see internal/bar).
func mounts(w func(int, string, ...any), depth int, host string, ms []mount, r spec.Robots, www string, private bool) {
	sm := make([]spec.Mount, len(ms))
	for i, m := range ms {
		sm[i] = m.Mount
	}
	w(depth, "handle /robots.txt {")
	w(depth+1, `header Content-Type "text/plain; charset=utf-8"`)
	w(depth+1, "respond <<ROBOTS")
	for _, l := range strings.Split(strings.TrimSuffix(robots.Text(host, r, sm, private), "\n"), "\n") {
		w(depth+2, "%s", l)
	}
	// A heredoc drops the newline before its closing marker: this blank
	// line gives the file its final newline.
	w(depth+2, "")
	w(depth+2, "ROBOTS 200")
	w(depth, "}")
	w(depth, "handle_path /_ddm/* {")
	w(depth+1, "root * %s", bar.Dir(www, private))
	w(depth+1, "file_server")
	w(depth, "}")
	slices.SortFunc(ms, func(a, b mount) int { return len(b.Path) - len(a.Path) })
	for _, m := range ms {
		root := publish.Current(www, m.View, m.Served)
		if m.Path == "/" {
			w(depth, "handle {")
		} else {
			w(depth, "redir %s %s/", m.Path, m.Path)
			w(depth, "handle_path %s/* {", m.Path)
		}
		if m.Entry != "" {
			w(depth+1, "redir / %s", strings.TrimSuffix(m.Path, "/")+m.Entry)
		}
		if m.Index != "" {
			w(depth+1, "@elsewhere not path / /%s/* /odoc.support/*", m.Package)
			w(depth+1, "redir @elsewhere %s{uri}", m.Index)
		}
		w(depth+1, "root * %s", root)
		w(depth+1, "file_server")
		w(depth, "}")
	}
}

// blocks groups mounts into site blocks. A domain's apex and anything more
// than one label below it get a block of their own; direct subdomains
// share a *.domain block. The private domain is grouped the same way, but
// never with the public domain it sits under.
func blocks(s *spec.Spec, t Target) []block {
	preview, port := t.Preview, t.Port
	byAddr := map[string]*block{}
	for _, name := range s.SiteNames() {
		for _, m := range s.Sites[name].Mounts {
			private := m.Access == spec.AccessPrivate
			addr := m.Host
			if !preview {
				apex := s.DomainOf(m.Host)
				if private {
					apex = s.PrivateDomain
				}
				if label, rest, _ := strings.Cut(m.Host, "."); rest == apex && label != "" {
					addr = "*." + apex
				}
			} else {
				addr = fmt.Sprintf("http://%s:%d", PreviewHost(m.Host), port)
			}
			bl, ok := byAddr[addr]
			if !ok {
				bl = &block{Address: addr, Private: private, Hosts: map[string][]mount{}}
				byAddr[addr] = bl
			}
			mm := mount{Mount: m, Site: name, Served: s.Served(name, m.View)}
			mm.Package, mm.Index = poolIndex(s, t, name, m)
			bl.Hosts[m.Host] = append(bl.Hosts[m.Host], mm)
		}
	}
	out := make([]block, 0, len(byAddr))
	for _, a := range slices.Sorted(maps.Keys(byAddr)) {
		out = append(out, *byAddr[a])
	}
	return out
}

// poolIndex returns, for a pool member with a repo and an entry, its
// package path (the entry's first segment) and the URL of the pool's index:
// the first mount, in the same view, of a member without a repo.
func poolIndex(s *spec.Spec, t Target, site string, m spec.Mount) (pkg, index string) {
	wf := s.PoolOf(site, m.View)
	if wf == "" || s.Sites[site].Repo == "" || m.Entry == "" {
		return "", ""
	}
	pkg, _, _ = strings.Cut(strings.Trim(m.Entry, "/"), "/")
	for _, other := range s.PoolMembers(wf, m.View) {
		if s.Sites[other].Repo != "" {
			continue
		}
		for _, om := range s.Sites[other].Mounts {
			if om.View == m.View {
				return pkg, t.Base(om.Host) + strings.TrimSuffix(om.Path, "/")
			}
		}
	}
	return "", ""
}

// notFoundRoot is where 404.html is served from: the public view of the
// first site built by the site-directory builtin, or "" if there is none.
func notFoundRoot(s *spec.Spec, www string) string {
	for _, name := range s.SiteNames() {
		v, ok := s.Sites[name].Views[spec.DefaultView]
		if !ok {
			continue
		}
		for _, st := range s.Workflows[v.Workflow].Steps {
			if st.Builtin == "site-directory" {
				return publish.Current(www, spec.DefaultView, name)
			}
		}
	}
	return ""
}
