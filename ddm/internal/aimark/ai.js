// ddm's AI-generated marker (see aimark.go and D56). Loaded as a module on
// every published page, next to the toolbar.
//
// Two <meta> tags in <head> say what is marked:
//   ddm:generated-site  added by ddm at publish from the site's `generated:`
//                       block, on the pages that block covers;
//   ddm:generated       added by the generator from a page's own `generated`
//                       front matter; wins over the site's. content="none"
//                       opts the page out.
// Both carry the author in `content` and the rest in data-model, data-effort,
// data-date, data-edited and data-selector (the part of the page to mark).
(() => {
  const read = (name) => {
    const m = document.head.querySelector(`meta[name="${name}"]`);
    if (!m) return null;
    const d = m.dataset;
    return {
      by: m.getAttribute("content") || "",
      model: d.model || "",
      effort: d.effort || "",
      date: d.date || "",
      edited: d.edited || "",
      selector: d.selector || "",
    };
  };

  const site = read("ddm:generated-site");
  const page = read("ddm:generated");
  if (page && page.by === "none") return;
  if (!site && !page) return;

  const g = { by: "Claude", model: "", effort: "", date: "", edited: "", selector: "" };
  for (const src of [site, page]) {
    if (!src) continue;
    for (const k of Object.keys(g)) if (src[k]) g[k] = src[k];
  }

  let target = document.body;
  if (g.selector) {
    try {
      target = document.querySelector(g.selector);
    } catch (e) {
      target = null;
    }
    // Marking more than was asked for would mislead; mark nothing.
    if (!target) {
      console.warn("ddm: generated selector matched nothing:", g.selector);
      return;
    }
  }
  const wholePage = target === document.body;

  const bar = document.createElement("div");
  bar.className = "ddm-ai-bar";
  bar.setAttribute("role", "note");
  const who = document.createElement("strong");
  who.textContent = `Generated by ${g.by}${g.model ? " " + g.model : ""}`;
  const bits = [`effort: ${g.effort || "unrecorded"}`];
  if (g.date) bits.push(`first ${g.date}`);
  if (g.edited) bits.push(`last edited ${g.edited}`);
  bar.append(who, ` · ${bits.join(" · ")}`);

  target.classList.add(wholePage ? "ddm-ai-page" : "ddm-ai-region");

  // A sticky site header (mkdocs-material's, say) would cover a bar stuck at
  // the top: put the bar after it and stick it just beneath.
  const header = document.querySelector("body > header, body > .md-header");
  const sticky = header && ["sticky", "fixed"].includes(getComputedStyle(header).position);
  if (wholePage && sticky) {
    header.after(bar);
  } else {
    target.prepend(bar);
  }
  if (sticky) {
    const follow = () => bar.style.setProperty("--ddm-ai-top", `${header.getBoundingClientRect().height}px`);
    follow();
    if (window.ResizeObserver) new ResizeObserver(follow).observe(header);
  }
})();
