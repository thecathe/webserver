// Package robots writes each host's robots.txt from the spec (D50): training
// crawlers are refused everywhere, AI assistants may fetch only the sites that
// allow them, and search engines (every other crawler) may index each mount
// as its search setting says. Private hosts refuse everything.
package robots

import (
	"fmt"
	"strings"

	"ddm/internal/spec"
)

// Assets a page needs to render, allowed alongside an entry page so search
// engines see it as visitors do. Images are not: they would be indexed too.
var assets = []string{"/_ddm/", "/fonts/", "/*.css$", "/*.js$", "/*.xsl$"}

// Text returns robots.txt for host, served by mounts ms (all on that host).
func Text(host string, r spec.Robots, ms []spec.Mount, private bool) string {
	var b strings.Builder
	line := func(format string, args ...any) { fmt.Fprintf(&b, format+"\n", args...) }
	line("# robots.txt for %s, generated by ddm from sites.yaml.", host)

	if private {
		line("# A private host: tailnet only, and never indexed.")
		line("User-agent: *")
		line("Content-Signal: search=no, ai-input=no, ai-train=no")
		line("Disallow: /")
		return b.String()
	}

	if len(r.Training) > 0 {
		line("")
		line("# AI training crawlers: refused everywhere.")
		for _, ua := range r.Training {
			line("User-agent: %s", ua)
		}
		line("Disallow: /")
	}

	assist := 0
	for _, m := range ms {
		if m.Assistants {
			assist++
		}
	}
	if len(r.Assistants) > 0 {
		line("")
		line("# AI assistants fetching a page for someone: only where a site allows it.")
		for _, ua := range r.Assistants {
			line("User-agent: %s", ua)
		}
		if assist == len(ms) {
			line("Allow: /")
		} else {
			for _, m := range ms {
				if m.Assistants {
					line("Allow: %s", prefix(m.Path))
				}
			}
			line("Disallow: /")
		}
	}

	line("")
	line("# Everyone else, search engines included.")
	line("User-agent: *")
	search, all := false, true
	for _, m := range ms {
		search = search || m.Search != spec.SearchNone
		all = all && m.Search == spec.SearchAll
	}
	line("Content-Signal: search=%s, ai-input=%s, ai-train=no", yesNo(search), yesNo(assist > 0))
	if all {
		line("Allow: /")
		return b.String()
	}
	entries := false
	for _, m := range ms {
		p := prefix(m.Path)
		switch m.Search {
		case spec.SearchAll:
			line("Allow: %s", p)
		case spec.SearchEntry:
			entries = true
			line("Allow: %s$", p)
			if e := strings.TrimPrefix(m.Entry, "/"); e != "" {
				line("Allow: %s%s$", p, e)
				if strings.HasSuffix(e, "/") {
					line("Allow: %s%sindex.html$", p, e)
				}
			} else {
				line("Allow: %sindex.html$", p)
			}
		}
	}
	if entries {
		for _, a := range assets {
			line("Allow: %s", a)
		}
	}
	line("Disallow: /")
	return b.String()
}

// prefix is a mount path as a robots.txt path prefix: "/" or "/sites/".
func prefix(path string) string {
	if path == "/" {
		return "/"
	}
	return strings.TrimSuffix(path, "/") + "/"
}

func yesNo(b bool) string {
	if b {
		return "yes"
	}
	return "no"
}
